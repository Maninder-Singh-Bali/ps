assert.equal(G.cutOpening(host,{kind:'window',points:[[50,-20],[50,20]],thickness:2},()=>''),null);
assert.deepEqual(G.cutOpening(host,{kind:'window',points:[[0,0],[100,0]],thickness:2},()=>''),[]);
const slopedHost={...host,points:[[0,0],[100,100]]};assert.equal(G.cutOpening(slopedHost,{kind:'window',points:[[30,30],[60,60]],thickness:2},()=>String(++nextId)).length,2);
assert.deepEqual(G.snapPoint([9,22],[[10,20]],3).point,[10,20]);assert.deepEqual(G.snapPoint([9,22],[[10,20]],.5).point,[9,22]);
assert.deepEqual(G.snapSegment([30,3],[host],4).point,[30,0]);assert.equal(G.snapSegment([120,3],[host],4),null);
assert.deepEqual(G.snapBounds([[0,0],[20,20]],[[22,30]],3).shift,[2,0]);
