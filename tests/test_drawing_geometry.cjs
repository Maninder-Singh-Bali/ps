const assert=require('node:assert/strict');
const {insert,resize,zoom,split,dragEndpoint,resizeOutline}=require('../static/drawing-geometry.js');
let n=0;const id=()=>`new${++n}`;
const wall={id:'newwall',kind:'wall',points:[[10,20],[110,20]],thickness:3,flip:false};
const original=JSON.stringify(wall);
const a=insert(wall,[70,21],[40,19],'window',id);
assert.deepEqual(a.features.map(x=>[x.kind,x.points]),[['wall',[[10,20],[40,20]]],['window',[[40,20],[70,20]]],['wall',[[70,20],[110,20]]]]);
assert.equal(JSON.stringify(wall),original);
assert.equal(new Set(a.features.map(x=>x.id)).size,3);
assert(a.features.every(x=>x.thickness===3));
const diagonal={...wall,points:[[0,0],[100,100]]};
assert.deepEqual(insert(diagonal,[20,20],[60,60],'window',id).features[1].points,[[20,20],[60,60]]);
assert.throws(()=>insert(wall,[0,20],[40,20],'window',id),/within/);
assert.throws(()=>insert(wall,[40,20],[40,20],'window',id),/different/);
assert.equal(insert(wall,[10,20],[110,20],'window',id).features.length,1);
assert.deepEqual(resize(wall,50,4,200,200).points,[[10,20],[60,20]]);
assert.throws(()=>resize(wall,500,3,200,200),/outside/);
const view=[10,20,100,200],anchor=[35,70],z=zoom(view,anchor,-100,100);
assert(z[2]<view[2]);assert.equal((anchor[0]-z[0])/z[2],.25);assert.equal((anchor[1]-z[1])/z[3],.25);
assert.deepEqual(view,[10,20,100,200]);
assert(zoom(view,anchor,1e9,100)[2]<=800);
const pieces=split(wall,[60,23],id);
assert.deepEqual(pieces.map(f=>f.points),[[[10,20],[60,20]],[[60,20],[110,20]]]);
assert(pieces.every(f=>f.kind==='wall'&&f.thickness===3));
assert.equal(new Set(pieces.map(f=>f.id)).size,2);
assert.equal(JSON.stringify(wall),original);
assert.throws(()=>split(wall,[10,20],id),/inside/);
assert.throws(()=>split(wall,[120,20],id),/inside/);
assert.throws(()=>split({...wall,kind:'window'},[60,20],id),/wall/);
assert.deepEqual(split(diagonal,[50,50],id).map(f=>f.points),[[[0,0],[50,50]],[[50,50],[100,100]]]);
const farWall={...wall,points:[[300,500],[400,500]]};
const endpoint=dragEndpoint(farWall,1,[10,4],1000,1000);
assert.deepEqual(endpoint.points,[[300,500],[410,500]]);
assert.equal(endpoint.thickness,3);
assert.deepEqual(dragEndpoint(farWall,0,[10,4],1000,1000).points,[[310,500],[400,500]]);
assert.deepEqual(dragEndpoint(farWall,1,[10,4],1000,1000,false).points,[[300,500],[410,504]]);
assert.deepEqual(dragEndpoint(farWall,1,[900,0],1000,1000).points,[[300,500],[1000,500]]);
// Repeated move events use the initial geometry; no accumulated scale or drift.
for(let i=0;i<100;i++)assert.deepEqual(dragEndpoint(farWall,1,[10,0],1000,1000),endpoint);
const box={x:300,y:500,width:100,height:10};
const anchored=resizeOutline({},box,[10,5]);
assert.equal(anchored.sx,1.1);assert.equal(anchored.sy,1.5);
assert(Math.abs(box.x*anchored.sx+anchored.dx-box.x)<1e-9);
assert(Math.abs(box.y*anchored.sy+anchored.dy-box.y)<1e-9);
function transformed(e,p){const a=(e.rotation||0)*Math.PI/180,x=(p[0]-(e.cx||0))*(e.sx||1),y=(p[1]-(e.cy||0))*(e.sy||1);return [(e.dx||0)+(e.cx||0)+Math.cos(a)*x-Math.sin(a)*y,(e.dy||0)+(e.cy||0)+Math.sin(a)*x+Math.cos(a)*y]}
const rotated={sx:2,sy:3,rotation:35,dx:45,dy:90,cx:50,cy:60};
const next=resizeOutline(rotated,box,[10,5]),oldAnchor=transformed(rotated,[300,500]),newAnchor=transformed(next,[300,500]);
assert(Math.hypot(newAnchor[0]-oldAnchor[0],newAnchor[1]-oldAnchor[1])<1e-9);
const oldCorner=transformed(rotated,[400,510]),newCorner=transformed(next,[400,510]);
assert(Math.abs(newCorner[0]-oldCorner[0]-10)<1e-9);assert(Math.abs(newCorner[1]-oldCorner[1]-5)<1e-9);
console.log('Drawing geometry: split, thickness preservation, anchored resize, rotated outlines and zoom checks passed');
const G=require('../static/drawing-geometry.js');
const host={id:'host',kind:'wall',points:[[0,0],[100,0]],thickness:4};let nextId=0;
